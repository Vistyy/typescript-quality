import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const exec = promisify(execFile);
const root = fileURLToPath(new URL("../", import.meta.url));
const readJson = async (path) => JSON.parse(await readFile(new URL(path, new URL("../", import.meta.url)), "utf8"));
const manifest = await readJson("package.json");
for (const tool of ["oxlint", "@biomejs/biome"]) {
  const installed = await readJson(`node_modules/${tool}/package.json`);
  if (installed.version !== manifest.devDependencies[tool]) {
    throw new Error(`Install the pinned ${tool} version before synchronizing rules.`);
  }
}
const run = async (command, args) => (await exec(command, args, {
  cwd: root, maxBuffer: 8 * 1024 * 1024,
})).stdout;
const isWarning = (setting) => ["warn", 1].includes(Array.isArray(setting) ? setting[0] : setting);
const asError = (setting) => Array.isArray(setting) ? ["error", ...setting.slice(1)] : "error";

// Inspect the unmodified selection policy, never the generated severity overlay.
const oxlint = JSON.parse(await run(process.execPath, [
  "node_modules/oxlint/bin/oxlint", "--config", "oxlint/policy.mjs", "--print-config",
]));
const inheritedErrors = Object.fromEntries(Object.entries(oxlint.rules)
  .filter(([, setting]) => isWarning(setting))
  .map(([name, setting]) => [name, asError(setting)]));

const biome = await readJson("biome/policy.json");
const schema = await readJson("node_modules/@biomejs/biome/configuration_schema.json");
const candidates = [];
for (const group of Object.keys(biome.linter.rules.recommended ? schema.$defs.Rules.properties : {})) {
  const definition = schema.$defs[group[0].toUpperCase() + group.slice(1)];
  for (const [name, property] of Object.entries(definition?.properties ?? {})) {
    if (property.description?.includes("https://biomejs.dev/linter/rules/")) candidates.push({ group, name });
  }
}
// Bound native process concurrency; documentation output can be substantial.
let index = 0;
const recommendedWarnings = [];
await Promise.all(Array.from({ length: 4 }, async () => {
  while (index < candidates.length) {
    const candidate = candidates[index++];
    const documentation = await run("node_modules/.bin/biome", ["explain", candidate.name]);
    const summary = documentation.split("Description")[0];
    if (/^- This rule is recommended$/m.test(summary) && /Default severity: warn/.test(summary)) {
      recommendedWarnings.push(candidate);
    }
  }
}));
recommendedWarnings.sort((a, b) => `${a.group}/${a.name}`.localeCompare(`${b.group}/${b.name}`, "en"));
let biomePromotions = 0;
for (const { group, name } of recommendedWarnings) {
  const rules = biome.linter.rules[group] ??= {};
  // Preserve explicit policy, including disabled rules and configured options.
  if (!(name in rules)) {
    rules[name] = "error";
    biomePromotions++;
  }
}

const outputs = {
  "oxlint/inherited-errors.mjs": `// Generated by scripts/sync-rule-severities.mjs; do not edit.\nexport default ${JSON.stringify(inheritedErrors, null, 2)};\n`,
  "biome/base.json": `${JSON.stringify(biome, null, 2)}\n`,
};
for (const [path, content] of Object.entries(outputs)) {
  const url = new URL(`../${path}`, import.meta.url);
  if (process.argv.includes("--check")) {
    const current = await readFile(url, "utf8").catch((error) => {
      if (error.code === "ENOENT") return "";
      throw error;
    });
    if (current !== content) throw new Error(`${path} is stale; run npm run sync:rules.`);
  } else {
    await writeFile(url, content);
  }
}
console.log(`Severity overlays: ${Object.keys(inheritedErrors).length} Oxlint warnings, ${biomePromotions} recommended Biome warnings.`);
